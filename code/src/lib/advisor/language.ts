const SETS = Object.fromEntries(LOCALES.map((l) => [l, new Set(WORDS[l])])) as Record<
  Locale,
  Set<string>
>;

/** Fewer distinct function words than this are too little evidence. */
const MIN_HITS = 2;

export function detectLanguage(text: string): Locale | null {
  const tokens = text.toLowerCase().match(/[\p{L}]+(?:'[\p{L}]+)?/gu) ?? [];
  if (tokens.length < 3) return null;
  // French elisions (j'ai, c'est) count as their two words.
  const words = tokens.flatMap((t) => (SETS.en.has(t) ? [t] : t.split("'")));
  const scores = LOCALES.map((locale) => ({
    locale,
    hits: words.filter((w) => SETS[locale].has(w)).length,
  })).sort((a, b) => b.hits - a.hits);
  const [best, second] = scores;
  if (best.hits < MIN_HITS || best.hits < second.hits * 2) return null;
  return best.locale;
}
