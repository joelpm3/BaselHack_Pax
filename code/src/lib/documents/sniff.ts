import type { AcceptedMimeType } from "./constants";

/**
 * Detects the real file type from its first bytes. The browser-supplied MIME type is not
 * trusted: a renamed file must not reach the model or the viewer with the wrong type.
 */
export function sniffMimeType(bytes: Uint8Array): AcceptedMimeType | null {
  const starts = (sig: number[], offset = 0) => sig.every((b, i) => bytes[offset + i] === b);
  if (starts([0x25, 0x50, 0x44, 0x46, 0x2d])) return "application/pdf"; // %PDF-
  if (starts([0xff, 0xd8, 0xff])) return "image/jpeg";
  if (starts([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) return "image/png";
  if (starts([0x52, 0x49, 0x46, 0x46]) && starts([0x57, 0x45, 0x42, 0x50], 8)) return "image/webp";
  return null;
}
